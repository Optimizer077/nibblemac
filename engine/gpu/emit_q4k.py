"""Emit our QPU programs and uniform-stream descriptors; MIT assembler dependency only.

python emit_q4k.py --assembler-src /path/to/py-videocore6/src --out q4kgpu_kernels.h
The C executable uses the generated header and needs no Python at runtime.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--assembler-src", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    if args.assembler_src:
        sys.path.insert(0, str(args.assembler_src))
    from _videocore6.assembler import assemble
    import q4kgpu

    lines = ["/* Generated by emit_q4k.py from our q4kgpu.py / qsched.py. Do not edit.",
             " * Plan: split; passes 1..8; 8 QPUs, one 16-lane workgroup each.",
             " * PARAM order is q4kgpu.PARAMS; stream tags describe every uniform word. */",
             "#ifndef PINFER_Q4KGPU_KERNELS_H", "#define PINFER_Q4KGPU_KERNELS_H",
             "#include <stdint.h>", "#include <stddef.h>",
             "enum q4kgpu_tag_kind { Q4KGPU_X, Q4KGPU_DX, Q4KGPU_NEGC_NEXT, Q4KGPU_NEGC, Q4KGPU_SUM8, Q4KGPU_FSUM };",
             "struct q4kgpu_tag { uint8_t kind, col, vec; };",
             "struct q4kgpu_program { unsigned n; const uint64_t *code; size_t words;",
             "  const struct q4kgpu_tag *start, *block; size_t start_words, block_words; };",
             "enum q4kgpu_param {"]
    for i, name in enumerate(q4kgpu.PARAMS):
        lines.append(f"  Q4KGPU_{name.upper()} = {i},")
    lines += [f"  Q4KGPU_PARAM_COUNT = {len(q4kgpu.PARAMS)}", "};"]
    for n in range(1, 9):
        kernel = q4kgpu.Kernel(n)
        code = assemble(kernel.program())
        lines.append(f"static const uint64_t q4kgpu_code_{n}[] = {{")
        lines.extend(f"  UINT64_C(0x{int(word):016x})," for word in code)
        lines.append("};")
        for part, tags in (("start", kernel.start_tags), ("block", kernel.block_tags)):
            lines.append(f"static const struct q4kgpu_tag q4kgpu_{part}_{n}[] = {{")
            for tag in tags:
                kind, col, vec = (tag[0].upper(), tag[1], tag[2]) if tag[0] == "x" else (tag[0].upper(), 0, tag[1])
                lines.append(f"  {{ Q4KGPU_{kind}, {col}, {vec} }},")
            lines.append("};")
        lines += [f"static const struct q4kgpu_program q4kgpu_program_{n} = {{",
                  f"  {n}, q4kgpu_code_{n}, sizeof(q4kgpu_code_{n}) / sizeof(uint64_t),",
                  f"  q4kgpu_start_{n}, q4kgpu_block_{n}, {len(kernel.start_tags)}, {len(kernel.block_tags)}", "};"]
        print(f"n={n}: {len(code)} instructions; {len(kernel.start_tags)} start / {len(kernel.block_tags)} block uniforms")
    lines += ["static const struct q4kgpu_program *const q4kgpu_programs[9] = {",
              "  NULL, " + ", ".join(f"&q4kgpu_program_{n}" for n in range(1, 9)), "};",
              "#endif", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
