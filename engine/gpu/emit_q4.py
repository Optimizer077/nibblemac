"""Emit our QPU programs and uniform-stream descriptors; MIT assembler dependency only.

python emit_q4.py --assembler-src /path/to/py-videocore6/src --out q4gpu_kernels.h
The C executable uses the generated header and needs no Python at runtime.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--assembler-src", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    if args.assembler_src:
        sys.path.insert(0, str(args.assembler_src))
    from _videocore6.assembler import assemble
    import q4gpu

    lines = ["/* Generated by emit_q4.py from our q4gpu.py / qsched.py. Do not edit.",
             " * Plan: split; passes 7 and 8; 8 QPUs, one 16-lane workgroup each.",
             " * PARAM order is q4gpu.PARAMS; stream tags describe every uniform word. */",
             "#ifndef PINFER_Q4GPU_KERNELS_H", "#define PINFER_Q4GPU_KERNELS_H",
             "#include <stdint.h>", "#include <stddef.h>",
             "enum q4gpu_tag_kind { Q4GPU_X, Q4GPU_DX, Q4GPU_NEGC_NEXT, Q4GPU_NEGC };",
             "struct q4gpu_tag { uint8_t kind, col, vec; };",
             "struct q4gpu_program { unsigned n; const uint64_t *code; size_t words;",
             "  const struct q4gpu_tag *start, *block; size_t start_words, block_words; };",
             "enum q4gpu_param {"]
    for i, name in enumerate(q4gpu.PARAMS):
        lines.append(f"  Q4GPU_{name.upper()} = {i},")
    lines += [f"  Q4GPU_PARAM_COUNT = {len(q4gpu.PARAMS)}", "};"]
    for n in (7, 8):
        kernel = q4gpu.Kernel(n)
        code = assemble(kernel.program())
        lines.append(f"static const uint64_t q4gpu_code_{n}[] = {{")
        lines.extend(f"  UINT64_C(0x{int(word):016x})," for word in code)
        lines.append("};")
        for part, tags in (("start", kernel.start_tags), ("block", kernel.block_tags)):
            lines.append(f"static const struct q4gpu_tag q4gpu_{part}_{n}[] = {{")
            for tag in tags:
                kind, col, vec = (tag[0].upper(), tag[1], tag[2]) if tag[0] == "x" else (tag[0].upper(), 0, tag[1])
                lines.append(f"  {{ Q4GPU_{kind}, {col}, {vec} }},")
            lines.append("};")
        lines += [f"static const struct q4gpu_program q4gpu_program_{n} = {{",
                  f"  {n}, q4gpu_code_{n}, sizeof(q4gpu_code_{n}) / sizeof(uint64_t),",
                  f"  q4gpu_start_{n}, q4gpu_block_{n}, {len(kernel.start_tags)}, {len(kernel.block_tags)}", "};"]
        print(f"n={n}: {len(code)} instructions; {len(kernel.start_tags)} start / {len(kernel.block_tags)} block uniforms")
    lines += ["#endif", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
